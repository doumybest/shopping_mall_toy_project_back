CREATE TABLE mall_events (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR2(100 CHAR) NOT NULL,
 description VARCHAR2(500 CHAR) NOT NULL,
 starts_at TIMESTAMP NOT NULL,
 ends_at TIMESTAMP NOT NULL,
 discount NUMBER(19) NOT NULL CHECK (discount >= 0),
 enabled NUMBER(1) NOT NULL CHECK (enabled IN (0, 1)),
 CONSTRAINT ck_event_dates CHECK (ends_at > starts_at)
);
CREATE TABLE mall_event_coupons (
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 event_id NUMBER(19) NOT NULL REFERENCES mall_events(id),
 discount NUMBER(19) NOT NULL CHECK (discount > 0),
 PRIMARY KEY (member_id, event_id)
);
ALTER TABLE mall_orders ADD (
 shipping_status VARCHAR2(20 CHAR) DEFAULT 'PREPARING' NOT NULL CHECK (shipping_status IN ('PREPARING', 'SHIPPED', 'DELIVERED')),
 coupon_event_id NUMBER(19),
 coupon_discount NUMBER(19) DEFAULT 0 NOT NULL CHECK (coupon_discount >= 0)
);
ALTER TABLE mall_orders DROP CONSTRAINT ck_order_amount;
ALTER TABLE mall_orders ADD CONSTRAINT ck_order_amount CHECK (subtotal = points_used + coupon_discount + amount_paid);
