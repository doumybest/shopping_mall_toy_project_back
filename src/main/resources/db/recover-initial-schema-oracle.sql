-- SYSTEM / FREEPDB1で先に実行: GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO mall;
-- MALL / FREEPDB1接続でF5実行。既存のテーブル・データは保持します。
-- 以前の構造で既存テーブルがある場合、完了後にV2/V3の更新SQLも確認してください。
SET SERVEROUTPUT ON;
DECLARE
  PROCEDURE ensure_object(p_name VARCHAR2, p_type VARCHAR2, p_ddl VARCHAR2) IS
    object_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO object_count FROM user_objects WHERE object_name=UPPER(p_name) AND object_type=p_type;
    IF object_count=0 THEN
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.PUT_LINE('Created ' || p_name);
    ELSE
      DBMS_OUTPUT.PUT_LINE('Exists ' || p_name);
    END IF;
  END;
BEGIN
  IF USER <> 'MALL' OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20001,'Connect as MALL to FREEPDB1.');
  END IF;
  ensure_object('mall_members', 'TABLE', q'~CREATE TABLE mall_members (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR2(200 CHAR) NOT NULL UNIQUE,
 password_hash VARCHAR2(100 CHAR) NOT NULL,
 name VARCHAR2(50 CHAR) NOT NULL,
 role VARCHAR2(10 CHAR) DEFAULT 'MEMBER' NOT NULL CHECK (role IN ('MEMBER','ADMIN')),
 points NUMBER(19) DEFAULT 0 NOT NULL,
 email_verified_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)~');
  ensure_object('mall_products', 'TABLE', q'~CREATE TABLE mall_products (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(120 CHAR) NOT NULL,
 category VARCHAR2(40 CHAR) NOT NULL,
 price NUMBER(19) NOT NULL CHECK (price BETWEEN 1 AND 100000000),
 description CLOB NOT NULL,
 emoji VARCHAR2(20 CHAR) NOT NULL,
 image_url VARCHAR2(1000 CHAR),
 stock NUMBER(10) DEFAULT 0 NOT NULL CHECK (stock >= 0),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
)~');
  ensure_object('mall_cart', 'TABLE', q'~CREATE TABLE mall_cart (
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 quantity NUMBER(10) NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 PRIMARY KEY (member_id,product_id)
)~');
  ensure_object('mall_wishlist', 'TABLE', q'~CREATE TABLE mall_wishlist (
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 PRIMARY KEY (member_id,product_id)
)~');
  ensure_object('mall_orders', 'TABLE', q'~CREATE TABLE mall_orders (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 request_key VARCHAR2(64 CHAR) NOT NULL,
 status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('PAID','CANCELLED')),
 subtotal NUMBER(19) NOT NULL,
 points_used NUMBER(19) NOT NULL CHECK (points_used >= 0),
 amount_paid NUMBER(19) NOT NULL CHECK (amount_paid >= 0),
 points_earned NUMBER(19) NOT NULL CHECK (points_earned >= 0),
 recipient VARCHAR2(50 CHAR) NOT NULL,
 phone VARCHAR2(30 CHAR) NOT NULL,
 address VARCHAR2(300 CHAR) NOT NULL,
 payment_method VARCHAR2(20 CHAR) NOT NULL CHECK (payment_method IN ('MOCK_CARD','MOCK_PAY')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 cancelled_at TIMESTAMP,
 CONSTRAINT uq_order_request UNIQUE (member_id,request_key),
 CONSTRAINT ck_order_amount CHECK (subtotal = points_used + amount_paid)
)~');
  ensure_object('mall_order_items', 'TABLE', q'~CREATE TABLE mall_order_items (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 product_name VARCHAR2(120 CHAR) NOT NULL,
 unit_price NUMBER(19) NOT NULL,
 quantity NUMBER(10) NOT NULL CHECK (quantity BETWEEN 1 AND 99)
)~');
  ensure_object('mall_payments', 'TABLE', q'~CREATE TABLE mall_payments (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 provider VARCHAR2(20 CHAR) DEFAULT 'MOCK' NOT NULL CHECK (provider = 'MOCK'),
 kind VARCHAR2(20 CHAR) NOT NULL CHECK (kind IN ('PAYMENT','REFUND')),
 amount NUMBER(19) NOT NULL CHECK (amount >= 0),
 reference_code VARCHAR2(100 CHAR) NOT NULL UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_payment_kind UNIQUE (order_id,kind)
)~');
  ensure_object('mall_point_ledger', 'TABLE', q'~CREATE TABLE mall_point_ledger (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 kind VARCHAR2(20 CHAR) NOT NULL CHECK (kind IN ('USE','EARN','RESTORE','REVOKE')),
 amount NUMBER(19) NOT NULL,
 balance_after NUMBER(19) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_point_entry UNIQUE (order_id,kind)
)~');
  ensure_object('mall_reviews', 'TABLE', q'~CREATE TABLE mall_reviews (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 rating NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
 content VARCHAR2(1000 CHAR) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_review_member UNIQUE (member_id,product_id)
)~');
  ensure_object('ix_orders_member', 'INDEX', q'~CREATE INDEX ix_orders_member ON mall_orders(member_id,id)~');
  ensure_object('ix_order_items_order', 'INDEX', q'~CREATE INDEX ix_order_items_order ON mall_order_items(order_id)~');
  ensure_object('ix_point_member', 'INDEX', q'~CREATE INDEX ix_point_member ON mall_point_ledger(member_id,id)~');
  ensure_object('ix_reviews_product', 'INDEX', q'~CREATE INDEX ix_reviews_product ON mall_reviews(product_id,id)~');
  ensure_object('mall_email_verifications', 'TABLE', q'~CREATE TABLE mall_email_verifications (
 email VARCHAR2(200 CHAR) PRIMARY KEY,
 code_hash VARCHAR2(100 CHAR),
 session_hash VARCHAR2(64 CHAR),
 expires_at TIMESTAMP,
 verified_at TIMESTAMP,
 consumed_at TIMESTAMP,
 sent_at TIMESTAMP,
 window_started_at TIMESTAMP NOT NULL,
 send_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (send_count >= 0),
 attempt_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (attempt_count BETWEEN 0 AND 5)
)~');
  ensure_object('mall_email_send_limits', 'TABLE', q'~CREATE TABLE mall_email_send_limits (
 source_hash VARCHAR2(64 CHAR) PRIMARY KEY,
 window_started_at TIMESTAMP NOT NULL,
 send_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (send_count >= 0)
)~');
END;
/
SELECT table_name FROM user_tables WHERE table_name LIKE 'MALL_%' ORDER BY table_name;
