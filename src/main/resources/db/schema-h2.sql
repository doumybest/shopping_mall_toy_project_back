CREATE TABLE IF NOT EXISTS mall_members (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR2(200 CHAR) NOT NULL UNIQUE,
 password_hash VARCHAR2(100 CHAR) NOT NULL,
 name VARCHAR2(50 CHAR) NOT NULL,
 role VARCHAR2(10 CHAR) DEFAULT 'MEMBER' NOT NULL CHECK (role IN ('MEMBER','ADMIN')),
 points NUMBER(19) DEFAULT 0 NOT NULL,
 email_verified_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS mall_products (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(120 CHAR) NOT NULL,
 category VARCHAR2(40 CHAR) NOT NULL,
 price NUMBER(19) NOT NULL CHECK (price BETWEEN 1 AND 100000000),
 description CLOB NOT NULL,
 emoji VARCHAR2(20 CHAR) NOT NULL,
 image_url VARCHAR2(1000 CHAR),
 stock NUMBER(10) DEFAULT 0 NOT NULL CHECK (stock >= 0),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS mall_cart (
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 quantity NUMBER(10) NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 PRIMARY KEY (member_id,product_id)
);
CREATE TABLE IF NOT EXISTS mall_wishlist (
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 PRIMARY KEY (member_id,product_id)
);
CREATE TABLE IF NOT EXISTS mall_orders (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 request_key VARCHAR2(64 CHAR) NOT NULL,
 status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('PAID','CANCELLED')),
 subtotal NUMBER(19) NOT NULL,
 points_used NUMBER(19) NOT NULL CHECK (points_used >= 0),
 amount_paid NUMBER(19) NOT NULL CHECK (amount_paid >= 0),
 points_earned NUMBER(19) NOT NULL CHECK (points_earned >= 0),
 recipient VARCHAR2(50 CHAR) NOT NULL,
 phone VARCHAR2(30 CHAR) NOT NULL,
 address VARCHAR2(300 CHAR) NOT NULL,
 payment_method VARCHAR2(20 CHAR) NOT NULL CHECK (payment_method IN ('MOCK_CARD','MOCK_PAY')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 cancelled_at TIMESTAMP,
 CONSTRAINT uq_order_request UNIQUE (member_id,request_key),
 CONSTRAINT ck_order_amount CHECK (subtotal = points_used + amount_paid)
);
CREATE TABLE IF NOT EXISTS mall_order_items (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 product_name VARCHAR2(120 CHAR) NOT NULL,
 unit_price NUMBER(19) NOT NULL,
 quantity NUMBER(10) NOT NULL CHECK (quantity BETWEEN 1 AND 99)
);
CREATE TABLE IF NOT EXISTS mall_payments (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 provider VARCHAR2(20 CHAR) DEFAULT 'MOCK' NOT NULL CHECK (provider = 'MOCK'),
 kind VARCHAR2(20 CHAR) NOT NULL CHECK (kind IN ('PAYMENT','REFUND')),
 amount NUMBER(19) NOT NULL CHECK (amount >= 0),
 reference_code VARCHAR2(100 CHAR) NOT NULL UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_payment_kind UNIQUE (order_id,kind)
);
CREATE TABLE IF NOT EXISTS mall_point_ledger (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 order_id NUMBER(19) NOT NULL REFERENCES mall_orders(id),
 kind VARCHAR2(20 CHAR) NOT NULL CHECK (kind IN ('USE','EARN','RESTORE','REVOKE')),
 amount NUMBER(19) NOT NULL,
 balance_after NUMBER(19) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_point_entry UNIQUE (order_id,kind)
);
CREATE TABLE IF NOT EXISTS mall_reviews (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id NUMBER(19) NOT NULL REFERENCES mall_members(id),
 product_id NUMBER(19) NOT NULL REFERENCES mall_products(id),
 rating NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
 content VARCHAR2(1000 CHAR) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_review_member UNIQUE (member_id,product_id)
);
CREATE INDEX IF NOT EXISTS ix_orders_member ON mall_orders(member_id,id);
CREATE INDEX IF NOT EXISTS ix_order_items_order ON mall_order_items(order_id);
CREATE INDEX IF NOT EXISTS ix_point_member ON mall_point_ledger(member_id,id);
CREATE INDEX IF NOT EXISTS ix_reviews_product ON mall_reviews(product_id,id);
